export type LabelKey = keyof typeof en;

/** Languages whose dictionary is loaded on demand. English is always bundled and acts as the fallback. */
const DICTIONARY_LOADERS: Record<Exclude<UiLanguage, "en">, () => Promise<{ default: LabelDictionary }>> = {
  es: () => import("./dictionaries/es"),
  fr: () => import("./dictionaries/fr"),
  de: () => import("./dictionaries/de"),
  it: () => import("./dictionaries/it"),
};

const loadedDictionaries = new Map<UiLanguage, LabelDictionary>([["en", en]]);

/** Returns a dictionary that is already in memory (English always is), or null if it still has to be loaded. */
export function getLoadedDictionary(language: UiLanguage): LabelDictionary | null {
  return loadedDictionaries.get(language) ?? null;
}

/** Resolves the dictionary for a language: already in memory for English, a cached dynamic import for the others. */
export async function loadDictionary(language: UiLanguage): Promise<LabelDictionary> {
  const cached = loadedDictionaries.get(language);
  if (cached) {
    return cached;
  }
  const loader = DICTIONARY_LOADERS[language as Exclude<UiLanguage, "en">];
  if (!loader) {
    return en;
  }
  const dictionary = (await loader()).default;
  loadedDictionaries.set(language, dictionary);
  return dictionary;
}

/** Looks a key up in a dictionary, falling back to the bundled English text and finally to the key itself. */
export function resolveLabel(dictionary: LabelDictionary | null | undefined, key: LabelKey): string {
  return dictionary?.[key] ?? en[key] ?? key;
}

export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce((acc, [paramKey, value]) => {
    return acc.split(`{${paramKey}}`).join(String(value));
  }, template);
}
